import React from "react";
import { motion } from "framer-motion";
import { Link, Navigate, useNavigate, useParams } from "react-router-dom";
import { FontAwesomeIcon } from "@fortawesome/react-fontawesome";
import {
  faTriangleExclamation,
  faPhone,
  faArrowRight,
  faRotateLeft,
  faHouse,
  faPrint,
} from "@fortawesome/free-solid-svg-icons";
import ResultMeter from "../components/ResultMeter";
import { useAppContext } from "../context/AppContext";
import { medicalDisclaimer } from "../data/assessmentMeta";
import { calculateAssessment, getAssessment } from "../data";
import { getConditionTheme } from "../uiTheme";

const crisisResources = [
  { title: "Tele-MANAS", contact: "14416", href: "tel:14416" },
  { title: "Vandrevala", contact: "+91 9999 666 555", href: "tel:+919999666555" },
  { title: "Emergency", contact: "112", href: "tel:112" },
];

function PrintSummary({ assessment, result, answers, aiMessage, theme }) {
  const date = new Date().toLocaleDateString("en-IN", {
    year: "numeric", month: "long", day: "numeric"
  });

  return (
    <div className="print-summary" id="print-summary">
      {/* Header */}
      <div className="print-header">
        <div>
          <div className="print-logo">🧠 NeuroBright</div>
          <div className="print-tagline">Self-Screening Summary</div>
        </div>
        <div className="print-date">Date: {date}</div>
      </div>

      <hr className="print-divider" />

      {/* Banner */}
      <div className="print-banner" style={{ borderLeft: `4px solid ${theme.color}` }}>
        <p className="print-banner-title" style={{ color: theme.color }}>
          {assessment.fullTitle} — {result.range.label}
        </p>
        <p className="print-banner-score">
          Score: <strong>{result.score} / {result.maxScore}</strong>
        </p>
        <p className="print-banner-note">{result.range.summary}</p>
      </div>

      {/* AI personal note */}
      {aiMessage && (
        <div className="print-ai-section">
          <p className="print-section-label">A note generated for you</p>
          <p className="print-ai-text">"{aiMessage}"</p>
        </div>
      )}

      {/* Question responses */}
      <div>
        <p className="print-section-label">Your responses</p>
        <table className="print-table">
          <thead>
            <tr>
              <th>Question</th>
              <th>Your Answer</th>
            </tr>
          </thead>
          <tbody>
            {assessment.questions.map((q) => (
              <tr key={q.id}>
                <td>{q.text}</td>
                <td>{answers[q.id]?.label ?? "—"}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>

      {/* Conversation starters */}
      <div className="print-conversation">
        <p className="print-section-label">Conversation starters for your doctor</p>
        <ul>
          <li>"I completed a validated {assessment.fullTitle} screener and scored {result.score}/{result.maxScore}, which corresponds to the <em>{result.range.label}</em> range."</li>
          <li>"I'd like to discuss whether these symptoms are consistent with a clinical picture worth exploring further."</li>
          <li>"Can you help me understand what formal assessment or next steps would be appropriate?"</li>
        </ul>
      </div>

      {/* Disclaimer */}
      <div className="print-disclaimer">
        <strong>Medical disclaimer: </strong>{medicalDisclaimer}
        <br />
        <span>This summary was generated by NeuroBright (neurobright.app) and is intended as a self-screening conversation aid only.</span>
      </div>
    </div>
  );
}

export default function Results() {
  const { type } = useParams();
  const navigate = useNavigate();
  const assessment = getAssessment(type);
  const { responses, results, resetAssessment, saveResult } = useAppContext();
  const answers = responses[type] ?? {};

  if (!assessment) return <Navigate to="/" replace />;

  const computedResult = calculateAssessment(type, answers);
  const result = results[type] ?? computedResult;
  const theme = getConditionTheme(assessment.id);

  const [aiMessage, setAiMessage] = React.useState(null);
  const [isAiLoading, setIsAiLoading] = React.useState(true);

  React.useEffect(() => {
    let active = true;
    async function fetchInsights() {
      try {
        setIsAiLoading(true);
        const { generateResultInsights } = await import("../services/llmService.js");
        const msg = await generateResultInsights(assessment, result, answers);
        if (active) setAiMessage(msg);
      } catch (e) {
        console.error("LLM Error:", e);
        if (active) setAiMessage("You took a brave step today. Whatever your results show, you deserve care and support. 💛");
      } finally {
        if (active) setIsAiLoading(false);
      }
    }

    if (result?.completed && !aiMessage && isAiLoading) {
      fetchInsights();
    }
    return () => { active = false; };
  }, [assessment, result, answers, aiMessage, isAiLoading]);

  React.useEffect(() => {
    if (computedResult?.completed && !results[type]) {
      saveResult(type, computedResult);
    }
  }, [computedResult, results, saveResult, type]);

  if (!result?.completed) {
    return <Navigate to={`/assessment/${type}/intro`} replace />;
  }

  const flaggedSelfHarmItem =
    type === "depression" &&
    typeof answers["depression-9"]?.value === "number" &&
    answers["depression-9"].value > 0;

  function handleRetake() {
    resetAssessment(type);
    navigate(`/assessment/${type}/quiz`);
  }

  function handlePrint() {
    window.print();
  }

  return (
    <>
      {/* ── Print-only summary (hidden on screen) ────────────── */}
      <PrintSummary
        assessment={assessment}
        result={result}
        answers={answers}
        aiMessage={aiMessage}
        theme={theme}
      />

      {/* ── Normal screen layout ─────────────────────────────── */}
      <motion.div
        initial={{ opacity: 0, y: 14 }}
        animate={{ opacity: 1, y: 0 }}
        exit={{ opacity: 0, y: -10 }}
        transition={{ duration: 0.3, ease: "easeOut" }}
        className="results-page-shell no-print"
      >
        {/* Left Column */}
        <div className="results-left">
          <ResultMeter
            score={result.score}
            maxScore={result.maxScore}
            label={result.range.label}
            caption={result.range.summary}
            assessmentId={assessment.id}
          />

          <motion.div
            initial={{ opacity: 0, scale: 0.97 }}
            animate={{ opacity: 1, scale: 1 }}
            transition={{ delay: 0.2, duration: 0.5 }}
            className="results-ai-card"
            style={{
              background: `linear-gradient(135deg, ${theme.colorLight} 0%, white 100%)`,
              border: `1.5px solid ${theme.colorLight}`,
              boxShadow: `0 12px 40px ${theme.colorLight}99`,
            }}
          >
            <h3 className="results-ai-title" style={{ color: theme.color }}>
              A Note Just For You 🌟
            </h3>
            {isAiLoading ? (
              <div className="results-ai-loading">Writing some warm thoughts…</div>
            ) : (
              <p className="results-ai-text">{aiMessage}</p>
            )}
          </motion.div>
        </div>

        {/* Right Column */}
        <div className="results-right">
          <div className="card results-detail-card">
            <span
              className={`badge badge--${assessment.id}`}
              style={{ marginBottom: "var(--sp-4)", display: "inline-flex" }}
            >
              {assessment.fullTitle}
            </span>

            <div
              style={{
                background: "var(--color-surface-alt)",
                borderRadius: "var(--r-lg)",
                padding: "0 var(--sp-4)",
              }}
            >
              <div className="detail-grid">
                <div className="detail-row">
                  <span className="detail-label">Your score</span>
                  <span className="detail-value">{result.score} / {result.maxScore}</span>
                </div>
                <div className="detail-row">
                  <span className="detail-label">Result</span>
                  <span className="detail-value" style={{ fontWeight: 700, color: theme.color }}>{result.range.label}</span>
                </div>
                <div className="detail-row">
                  <span className="detail-label">Use this as</span>
                  <span className="detail-value">A starting point for a clinical conversation</span>
                </div>
                <div className="detail-row">
                  <span className="detail-label">Best next move</span>
                  <span className="detail-value">Review support options if symptoms affect daily life</span>
                </div>
              </div>
            </div>
          </div>

          {flaggedSelfHarmItem && (
            <div className="crisis-alert">
              <p className="crisis-alert-title">
                <FontAwesomeIcon icon={faTriangleExclamation} />
                Please reach out now if you feel unsafe.
              </p>
              <p style={{ fontSize: "var(--text-sm)", color: "var(--color-danger-text)", lineHeight: 1.65 }}>
                You marked the PHQ-9 item about self-harm above zero. If you may act on these thoughts, contact an urgent support line or local emergency services now.
              </p>
              <div className="crisis-links">
                {crisisResources.map((r) => (
                  <a key={r.title} href={r.href} className="btn btn--danger btn--sm">
                    <FontAwesomeIcon icon={faPhone} />
                    {r.title}: {r.contact}
                  </a>
                ))}
              </div>
            </div>
          )}

          <div className="results-ctas">
            <Link
              to="/referral?auto=true"
              className="btn btn--primary"
              style={{
                background: theme.color,
                borderColor: theme.color,
                boxShadow: `0 4px 14px 0 ${theme.color}44`,
                justifyContent: "center",
              }}
            >
              Find Support Near You 📍
              <FontAwesomeIcon icon={faArrowRight} />
            </Link>

            <button
              type="button"
              onClick={handlePrint}
              className="btn btn--outline"
              style={{ justifyContent: "center" }}
            >
              <FontAwesomeIcon icon={faPrint} />
              Print doctor's summary
            </button>

            <button type="button" onClick={handleRetake} className="btn btn--outline">
              <FontAwesomeIcon icon={faRotateLeft} />
              Retake this assessment
            </button>
            <Link to="/" className="btn btn--ghost">
              <FontAwesomeIcon icon={faHouse} />
              Try another assessment
            </Link>
          </div>

          <div className="disclaimer">
            <strong>Important disclaimer: </strong>
            {medicalDisclaimer}
          </div>
        </div>
      </motion.div>
    </>
  );
}
